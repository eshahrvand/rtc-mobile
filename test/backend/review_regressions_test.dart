const branch = BranchInfo(
  id: '1',
  name: 'تهران',
  province: 'تهران',
  city: 'تهران',
  postalCode: '',
  address: '',
);

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  setUpAll(() => S.load(const Locale('fa')));

  test(
    'shared PDF path converts HTML and saves generated bytes for policies and invoices',
    () async {
      final directory = await Directory.systemTemp.createTemp('rtc_pdf_path_');
      final messenger =
          TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger;
      const paths = MethodChannel('plugins.flutter.io/path_provider');
      const converter = MethodChannel('flutter_native_html_to_pdf');
      final converted = <String>[];
      var failSaving = false;
      messenger.setMockMethodCallHandler(paths, (_) async => directory.path);
      messenger.setMockMethodCallHandler(converter, (call) async {
        expect(call.method, 'convertHtmlToPdf');
        final name = call.arguments['targetName'] as String;
        expect(call.arguments['html'], contains('<html'));
        converted.add(name);
        final file = File('${directory.path}/$name.pdf');
        await file.writeAsBytes([37, 80, 68, 70]);
        return file.path;
      });
      messenger.setMockMethodCallHandler(HtmlDocumentExporter.channel, (
        call,
      ) async {
        expect(call.method, 'saveToDownloads');
        if (failSaving) return null;
        final file = File(
          '${directory.path}/download_${call.arguments['fileName']}.pdf',
        );
        await file.writeAsBytes(
          List<int>.from(call.arguments['bytes'] as List),
        );
        return file.path;
      });
      addTearDown(() async {
        messenger.setMockMethodCallHandler(paths, null);
        messenger.setMockMethodCallHandler(converter, null);
        messenger.setMockMethodCallHandler(HtmlDocumentExporter.channel, null);
        await directory.delete(recursive: true);
      });
      for (final name in ['privacy_policy_3', 'pre_invoice_1']) {
        final result = await HtmlDocumentExporter.generateAndSave(
          '<html>قوانین</html>',
          name,
        );
        expect(await File(result.savedPath).readAsBytes(), [37, 80, 68, 70]);
        expect(result.generatedPath, '${directory.path}/$name.pdf');
      }
      expect(converted, ['privacy_policy_3', 'pre_invoice_1']);
      failSaving = true;
      await expectLater(
        HtmlDocumentExporter.export('<html>قوانین</html>', 'failure'),
        throwsStateError,
      );
    },
  );

  test(
    'dashboard only displays translated statuses, with known ordering and counts',
    () {
      final items = DashboardMapper.mapOrderStatusChart([
        const OrderStatusDtoModel(status: 'canceled', count: 70),
        const OrderStatusDtoModel(status: 'future_status', count: 90),
        const OrderStatusDtoModel(status: 'pre_invoice', count: 3),
        const OrderStatusDtoModel(status: 'approved', count: 2),
      ]);
      expect(items.map((item) => item.label), [
        S.current.statusApproved,
        S.current.preInvoice,
      ]);
      expect(items.map((item) => item.value), [2, 3]);
      expect(
        DashboardMapper.mapOrderStatusChart([
          const OrderStatusDtoModel(status: 'canceled', count: 1),
        ]),
        isEmpty,
      );
    },
  );

  testWidgets(
    'branch search waits one second, uses server query, ignores stale responses and cancels on close',
    (tester) async {
      final queries = <String>[];
      final responses = <String, Completer<List<BranchInfo>>>{};
      final cubit = WorkspaceCubit(
        WorkspaceRepository(
          searchBranches: (query) {
            queries.add(query);
            return (responses[query] = Completer<List<BranchInfo>>()).future;
          },
        ),
      );
      cubit.searchBranches('ت');
      await tester.pump(const Duration(milliseconds: 999));
      expect(queries, isEmpty);
      cubit.searchBranches('ته');
      await tester.pump(const Duration(seconds: 1));
      expect(queries, ['ته']);
      cubit.searchBranches('تهران');
      responses['ته']!.complete([branch]);
      await tester.pump();
      expect(cubit.state.branches, isEmpty);
      await tester.pump(const Duration(seconds: 1));
      expect(queries, ['ته', 'تهران']);
      responses['تهران']!.complete([branch]);
      await tester.pump();
      expect(cubit.state.branches.single.id, '1');
      cubit.searchBranches('لغو');
      await cubit.close();
      await tester.pump(const Duration(seconds: 1));
      expect(queries, ['ته', 'تهران']);
    },
  );

  test(
    'policy download fetches protected HTML, converts and saves PDF before showing success',
    () async {
      final saved = Completer<String>();
      final calls = <String>[];
      final cubit = WorkspaceCubit(
        WorkspaceRepository(
          loadPolicyHtml: (id) {
            calls.add(id);
            return Future.value('<html dir="rtl">قوانین</html>');
          },
        ),
        initialState: const WorkspaceState(
          terms: TermsDocument(
            id: 'policy-id',
            version: '3',
            versionLabel: 'نسخه ۳',
            markdown: '',
            publishedAt: '',
          ),
        ),
        exportHtml: (html, name) {
          expect(html, contains('قوانین'));
          expect(name, 'privacy_policy_policy-id');
          return saved.future;
        },
      );
      addTearDown(cubit.close);
      cubit.downloadTerms();
      cubit.downloadTerms();
      await Future<void>.delayed(Duration.zero);
      expect(calls, ['policy-id']);
      expect(cubit.state.policyDownloadLoading, isTrue);
      expect(cubit.state.policyDownloadSaved, isFalse);
      saved.complete('/Download/privacy_policy_policy-id.pdf');
      await Future<void>.delayed(Duration.zero);
      expect(cubit.state.policyDownloadLoading, isFalse);
      expect(cubit.state.policyDownloadSaved, isTrue);
    },
  );
}
